export function detectLang(config) {
  const wanted = config?.language;
  if (wanted && STRINGS[wanted]) return wanted;
  const env = process.env.AGYSTATUSLINE_LANG || process.env.LC_ALL || process.env.LC_MESSAGES || process.env.LANG || "";
  return /^zh/i.test(env) ? "zh" : "en";
}

export function t(lang, key, ...args) {
  const table = STRINGS[lang] ?? STRINGS.en;
  let text = table[key] ?? STRINGS.en[key] ?? key;
  args.forEach((value, i) => {
    text = text.replace(`{${i}}`, String(value));
  });
  return text;
}

export const translator = (lang) => (key, ...args) => t(lang, key, ...args);

// Widget type names are shown in the editor only; the rendered status line
// keeps the raw values, so translations never leak into agy's output.
export function widgetName(lang, type) {
  const table = STRINGS[lang];
  return (table && table[`widget.${type}`]) || type;
}
